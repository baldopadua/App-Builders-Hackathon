"""Gate 3 step 1: download the pinned ALT and Tatoeba files, extract fil/en pairs, filter, check for overlap with the
evaluation sets, and record everything in gate3/data-manifest.json.

Downloads and processed data go to $GATE3_WORK/data (outside the repo). Only the manifest is committed.
    <venv>\\Scripts\\python.exe "AI Model\\ai-local\\gate3\\train\\prepare_data.py"
"""
import datetime
import gzip
import json
import sys
from importlib.metadata import version

import pyarrow.parquet as pq

from common import (ALT, DATA, MANIFEST, NOTES_SET, TATOEBA, fetch, hf_url, normalize, notes_set_texts, sha256_file,
                    write_tsv)

MIN_RATIO, MAX_RATIO = 0.4, 2.5   # character-length ratio fil/en outside this = likely misaligned
MIN_CONTAINED_WORDS = 6           # an eval sentence this long found inside an ALT sentence counts as overlap


def download(repo, filename, revision, expected_sha=None):
    local = DATA / "raw" / repo.replace("/", "__") / filename
    return local, fetch(hf_url(repo, revision, filename, dataset=True), local, expected_sha)


def load_tatoeba():
    raw, digest = download(TATOEBA["repo"], TATOEBA["file"], TATOEBA["revision"])
    pairs = []
    with gzip.open(raw, "rt", encoding="utf-8") as f:
        for line in f:
            o = json.loads(line)
            pairs.append((o["sentence1"].strip(), o["sentence2"].strip()))   # tgl, eng
    return raw, digest, pairs


def alt_pairs(path):
    rows = pq.read_table(path, columns=["translation"]).column("translation").to_pylist()
    return [((t or {}).get("fil") or "", (t or {}).get("en") or "") for t in rows]


def filter_pairs(pairs, eval_exact, eval_long, seen):
    counts = {"rows": len(pairs)}
    out = []

    def drop(reason):
        counts[reason] = counts.get(reason, 0) + 1

    for fil, en in pairs:
        fil, en = " ".join(fil.split()), " ".join(en.split())
        if not fil or not en:
            drop("dropped_empty_side"); continue
        nf, ne = normalize(fil), normalize(en)
        if nf == ne:
            drop("dropped_untranslated"); continue
        ratio = len(fil) / max(1, len(en))
        if not MIN_RATIO <= ratio <= MAX_RATIO:
            drop("dropped_length_ratio"); continue
        if nf in eval_exact or ne in eval_exact:
            drop("dropped_eval_overlap_exact"); continue
        if any(s in nf or s in ne for s in eval_long):
            drop("dropped_eval_overlap_contained"); continue
        key = nf + "\t" + ne
        if key in seen:
            drop("dropped_duplicate"); continue
        seen.add(key)
        out.append((fil, en))
    counts["kept"] = len(out)
    return out, counts


def main():
    DATA.mkdir(parents=True, exist_ok=True)

    # ---- evaluation sets first: Tatoeba tgl-eng (untouched) + the private-note set --------------------------
    tat_raw, tat_sha, tatoeba = load_tatoeba()
    write_tsv(DATA / "tatoeba-tgl-eng.tsv", tatoeba)
    eval_texts = [s for p in tatoeba for s in p] + notes_set_texts()
    eval_norm = [normalize(s) for s in eval_texts]
    eval_exact = set(eval_norm)
    eval_long = sorted({s for s in eval_norm if len(s.split()) >= MIN_CONTAINED_WORDS})

    # ---- ALT: train + validation, filtered, deduplicated, no overlap with the evaluation sets --------------
    seen = set()
    alt_out = {}
    for split in ("train", "validation"):
        filename, expected = ALT["files"][split]
        raw, digest = download(ALT["repo"], filename, ALT["revision"], expected)
        pairs, counts = filter_pairs(alt_pairs(raw), eval_exact, eval_long, seen)   # validation also deduped vs train
        out = DATA / f"alt-{split}.tsv"
        write_tsv(out, pairs)
        alt_out[split] = {"file": filename, "sha256": digest, "counts": counts,
                          "processed": out.name, "processed_sha256": sha256_file(out)}
        print(f"ALT {split}: {counts}")

    # ---- verification: re-read what will be trained on and confirm zero overlap ---------------------------
    leaks = 0
    for split in ("train", "validation"):
        for line in (DATA / f"alt-{split}.tsv").read_text(encoding="utf-8").splitlines():
            fil, en = line.split("\t")
            nf, ne = normalize(fil), normalize(en)
            if nf in eval_exact or ne in eval_exact or any(s in nf or s in ne for s in eval_long):
                leaks += 1
    if leaks:
        sys.exit(f"{leaks} ALT pair(s) still overlap the evaluation sets")
    print(f"Tatoeba tgl-eng: {len(tatoeba)} pairs. Overlap check: 0 ALT pairs match the evaluation sets.")

    manifest = {
        "_note": "Generated by gate3/train/prepare_data.py. The data itself lives outside the repo ($GATE3_WORK/data) and never ships in the app.",
        "generated": datetime.date.today().isoformat(),
        "training": {
            "name": "ALT parallel corpus (fil-en)", "repo": ALT["repo"], "revision": ALT["revision"],
            "license": ALT["license"], "attribution": ALT["attribution"], "splits": alt_out,
            "filters": {"length_ratio_fil_over_en": [MIN_RATIO, MAX_RATIO],
                        "eval_overlap": f"normalized exact match, or an eval sentence of >= {MIN_CONTAINED_WORDS} words contained in the pair",
                        "dedup": "normalized (fil, en) pair, across train and validation"},
        },
        "evaluation": {
            "tatoeba": {"name": "Tatoeba tgl-eng (MTEB bitext mining, test)", "repo": TATOEBA["repo"],
                        "revision": TATOEBA["revision"], "license": TATOEBA["license"], "attribution": TATOEBA["attribution"],
                        "file": TATOEBA["file"], "sha256": tat_sha, "pairs": len(tatoeba),
                        "processed": "tatoeba-tgl-eng.tsv", "processed_sha256": sha256_file(DATA / "tatoeba-tgl-eng.tsv")},
            "private_notes": {"file": "test-data/gate3/private-notes.json", "sha256": sha256_file(NOTES_SET),
                              "texts": len(notes_set_texts())},
            "flores_plus": "not used: gated; the plan does not depend on it",
        },
        "overlap_check": {"eval_sentences": len(eval_exact), "eval_sentences_checked_for_containment": len(eval_long),
                          "alt_pairs_overlapping_after_filtering": leaks},
        "environment": {p: version(p) for p in ("torch", "transformers", "huggingface_hub", "pyarrow", "numpy", "onnx", "onnxruntime")},
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {MANIFEST}")


if __name__ == "__main__":
    main()
