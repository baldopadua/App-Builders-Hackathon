# ============================================================================
# SecondLook AI Test App Build & Deploy Script
# For: Team testing on physical Android devices
# Platform: Windows PowerShell (7+) or Windows built-in PowerShell
# ============================================================================
# Usage:
#   .\BUILD_AND_TEST.ps1                    # Full menu
#   .\BUILD_AND_TEST.ps1 -Quick             # Fast build (less optimization)
#   .\BUILD_AND_TEST.ps1 -Install           # Build + install on connected phone
#   .\BUILD_AND_TEST.ps1 -Clean             # Clear build artifacts & gradle cache
# ============================================================================

param(
    [switch]$Quick,
    [switch]$Install,
    [switch]$Clean
)

$ErrorActionPreference = "Stop"
$WarningPreference = "Continue"

# Colors for output
$Green = "Green"
$Yellow = "Yellow"
$Red = "Red"
$Blue = "Cyan"

# Paths
$RepoRoot = $PSScriptRoot
$TestAppDir = Join-Path $RepoRoot "test-app"
$GradlePropsFile = Join-Path $TestAppDir "gradle.properties"
$ApkDebug = Join-Path $TestAppDir "app\build\outputs\apk\debug\app-debug.apk"
$ApkRelease = Join-Path $TestAppDir "app\build\outputs\apk\release\app-release.apk"

# ============================================================================
# Helper Functions
# ============================================================================

function Write-Header {
    param([string]$Text)
    Write-Host "`n`n" -ForegroundColor $Blue
    Write-Host "╔════════════════════════════════════════════════════════╗" -ForegroundColor $Blue
    Write-Host "║  $($Text.PadRight(54))║" -ForegroundColor $Blue
    Write-Host "╚════════════════════════════════════════════════════════╝" -ForegroundColor $Blue
    Write-Host ""
}

function Write-Success {
    param([string]$Text)
    Write-Host "✓ $Text" -ForegroundColor $Green
}

function Write-Warning {
    param([string]$Text)
    Write-Host "⚠ $Text" -ForegroundColor $Yellow
}

function Write-Error-Custom {
    param([string]$Text)
    Write-Host "✗ $Text" -ForegroundColor $Red
}

function Check-Prerequisites {
    Write-Header "Checking Prerequisites"
    
    # Check JDK
    $javaVersion = java -version 2>&1
    if ($LASTEXITCODE -ne 0) {
        Write-Error-Custom "Java/JDK not found. Install JDK 17 or later."
        Write-Host "Download: https://adoptium.net/"
        exit 1
    }
    Write-Success "Java detected"
    
    # Check Android SDK
    $androidSdkPath = $env:ANDROID_HOME
    if (-not $androidSdkPath -or -not (Test-Path $androidSdkPath)) {
        Write-Warning "ANDROID_HOME not set. Android Studio typically sets this."
        Write-Host "If ADB is not found, install Android Studio or set ANDROID_HOME manually."
    } else {
        Write-Success "Android SDK found at: $androidSdkPath"
    }
    
    # Check if ADB is available
    $adbPath = "$androidSdkPath\platform-tools\adb.exe"
    if (-not (Test-Path $adbPath)) {
        $adbPath = (Get-Command adb -ErrorAction SilentlyContinue).Path
        if (-not $adbPath) {
            Write-Warning "ADB not found. Cannot install on device."
            Write-Host "Device installation will be skipped."
            return $false
        }
    }
    Write-Success "ADB found"
    return $true
}

function Get-ConnectedDevices {
    $adbPath = $env:ANDROID_HOME
    if (Test-Path "$adbPath\platform-tools\adb.exe") {
        $adb = "$adbPath\platform-tools\adb.exe"
    } else {
        $adb = "adb"
    }
    
    $devices = & $adb devices 2>&1 | Select-Object -Skip 1 | Where-Object { $_ -and -not $_.StartsWith("List") }
    return @($devices | Where-Object { $_ -match "^\w+.*device$" })
}

function Configure-Gradle-Memory {
    param(
        [string]$Profile = "balanced"  # balanced, aggressive, conservative
    )
    
    Write-Header "Configuring Gradle Build Memory"
    
    $config = switch ($Profile) {
        "aggressive" {
            @{
                xmx = "5120m"
                metaspace = "1024m"
                workers = 4
                parallel = "true"
            }
        }
        "conservative" {
            @{
                xmx = "2048m"
                metaspace = "512m"
                workers = 1
                parallel = "false"
            }
        }
        default {  # balanced
            @{
                xmx = "3072m"
                metaspace = "768m"
                workers = 2
                parallel = "true"
            }
        }
    }
    
    $content = @"
# Gradle Memory & Performance Configuration
# Profile: $Profile
# Generated by BUILD_AND_TEST.ps1
org.gradle.jvmargs=-Xmx$($config.xmx) -XX:MaxMetaspaceSize=$($config.metaspace) -Dfile.encoding=UTF-8
org.gradle.parallel=$($config.parallel)
org.gradle.workers.max=$($config.workers)
org.gradle.caching=true

# Android configuration
android.useAndroidX=false
android.nonTransitiveRClass=true
android.enableBuildScriptClasspathValidation=false

# Kotlin configuration
kotlin.code.style=official
"@
    
    Set-Content -Path $GradlePropsFile -Value $content
    Write-Success "Gradle configured with profile: $Profile"
    Write-Host "  JVM args: -Xmx$($config.xmx) -XX:MaxMetaspaceSize=$($config.metaspace)"
    Write-Host "  Workers: $($config.workers), Parallel: $($config.parallel)"
}

function Stop-Gradle-Daemons {
    Write-Header "Stopping Gradle Daemons"
    
    Push-Location $TestAppDir
    & .\gradlew.bat --stop 2>&1 | ForEach-Object { if ($_) { Write-Host $_ } }
    Pop-Location
    
    Start-Sleep -Seconds 2
    Write-Success "Gradle daemons stopped"
}

function Clean-Build {
    Write-Header "Cleaning Build Artifacts"
    
    Push-Location $TestAppDir
    & .\gradlew.bat clean 2>&1 | Tee-Object -Variable cleanOutput | Out-Null
    Pop-Location
    
    if ($LASTEXITCODE -eq 0) {
        Write-Success "Build artifacts cleaned"
    } else {
        Write-Error-Custom "Clean failed (non-critical, continuing...)"
    }
}

function Build-APK {
    param(
        [string]$BuildType = "debug",  # debug or release
        [switch]$Incremental
    )
    
    $buildTask = if ($BuildType -eq "release") { "assembleRelease" } else { "assembleDebug" }
    
    Write-Header "Building APK ($BuildType)"
    Write-Host "This may take 2-5 minutes on first build..."
    Write-Host ""
    
    Push-Location $TestAppDir
    
    $gradleArgs = @(".\gradlew.bat", $buildTask)
    
    # Only use incremental flags if explicitly requested
    if ($Incremental) {
        $gradleArgs += @(
            "-Pkotlin.incremental=true",
            "-Pkotlin.compiler.execution.strategy=in-process"
        )
    }
    
    $startTime = Get-Date
    & @gradleArgs 2>&1 | Tee-Object -Variable buildOutput | Out-Null
    $endTime = Get-Date
    $duration = ($endTime - $startTime).TotalSeconds
    
    Pop-Location
    
    if ($LASTEXITCODE -eq 0) {
        Write-Success "APK built successfully in $([math]::Round($duration, 1)) seconds"
        return $true
    } else {
        Write-Error-Custom "Build failed!"
        Write-Host ""
        Write-Host "Troubleshooting:" -ForegroundColor $Yellow
        Write-Host "1. Close other applications to free RAM"
        Write-Host "2. Try: .\BUILD_AND_TEST.ps1 -Clean   (clears cache)"
        Write-Host "3. Try: .\BUILD_AND_TEST.ps1 -Quick   (faster build)"
        Write-Host "4. Check logs: $TestAppDir\.gradle\daemon\*\daemon-*.out.log"
        return $false
    }
}

function Install-APK-On-Device {
    param([string]$ApkPath)
    
    Write-Header "Installing APK on Connected Device"
    
    # Locate ADB
    $adbPath = $env:ANDROID_HOME
    if (Test-Path "$adbPath\platform-tools\adb.exe") {
        $adb = "$adbPath\platform-tools\adb.exe"
    } else {
        $adb = "adb"
    }
    
    # Check if file exists
    if (-not (Test-Path $ApkPath)) {
        Write-Error-Custom "APK not found: $ApkPath"
        return $false
    }
    
    # Check connected devices
    $devices = Get-ConnectedDevices
    if ($devices.Count -eq 0) {
        Write-Error-Custom "No Android devices found!"
        Write-Host ""
        Write-Host "Setup:" -ForegroundColor $Yellow
        Write-Host "1. Connect phone via USB"
        Write-Host "2. Allow USB Debugging when prompted"
        Write-Host "3. Enable Developer Options:"
        Write-Host "   Settings → About Phone → tap Build Number 7 times → USB Debugging ON"
        Write-Host ""
        Write-Host "Then run: $adb devices"
        return $false
    }
    
    Write-Host "Found $($devices.Count) device(s):"
    $devices | ForEach-Object { Write-Host "  • $_" }
    Write-Host ""
    
    # Use first device if multiple
    $targetDevice = ($devices[0] -split "\s+")[0]
    
    Write-Host "Installing to device: $targetDevice"
    & $adb -s $targetDevice install -r $ApkPath 2>&1 | Tee-Object -Variable installOutput | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Success "APK installed successfully!"
        Write-Host ""
        Write-Host "Next steps:" -ForegroundColor $Green
        Write-Host "1. On phone, open app drawer"
        Write-Host "2. Tap 'SecondLook AI test'"
        Write-Host "3. Follow testing guide: TESTING.md"
        return $true
    } else {
        Write-Error-Custom "Installation failed!"
        if ($installOutput -match "device is locked") {
            Write-Host "Hint: Unlock your phone and try again" -ForegroundColor $Yellow
        }
        return $false
    }
}

function Show-Menu {
    Write-Header "SecondLook AI Test App Builder"
    Write-Host ""
    Write-Host "1. Build Debug APK (balanced memory settings)"
    Write-Host "2. Build + Install on Phone"
    Write-Host "3. Build Release APK (unsigned, for sideload)"
    Write-Host "4. Clean & Rebuild (fixes memory errors)"
    Write-Host "5. Quick Build (low memory mode)"
    Write-Host "6. Check device connection"
    Write-Host "7. Exit"
    Write-Host ""
    $choice = Read-Host "Choose option (1-7)"
    return $choice
}

# ============================================================================
# Main Flow
# ============================================================================

function Main {
    Clear-Host
    
    Write-Host "SecondLook AI - Team Build Script" -ForegroundColor $Blue
    Write-Host "Repository: $RepoRoot" -ForegroundColor $Blue
    Write-Host ""
    
    # If command-line args provided, skip menu
    if ($Clean) {
        Stop-Gradle-Daemons
        Clean-Build
        exit 0
    }
    
    if ($Quick) {
        Check-Prerequisites | Out-Null
        Configure-Gradle-Memory -Profile "conservative"
        Stop-Gradle-Daemons
        if (Build-APK -BuildType "debug") {
            Write-Host ""
            Write-Host "APK ready: $ApkDebug" -ForegroundColor $Green
        }
        exit $LASTEXITCODE
    }
    
    if ($Install) {
        Check-Prerequisites | Out-Null
        Configure-Gradle-Memory -Profile "balanced"
        Stop-Gradle-Daemons
        if (Build-APK -BuildType "debug") {
            Install-APK-On-Device $ApkDebug
        }
        exit $LASTEXITCODE
    }
    
    # Interactive menu
    $adbAvailable = Check-Prerequisites
    
    while ($true) {
        $choice = Show-Menu
        
        switch ($choice) {
            "1" {
                Configure-Gradle-Memory -Profile "balanced"
                Stop-Gradle-Daemons
                Build-APK -BuildType "debug" | Out-Null
                Write-Host ""
                Write-Host "APK: $ApkDebug" -ForegroundColor $Green
            }
            "2" {
                if (-not $adbAvailable) {
                    Write-Error-Custom "ADB not available. Cannot install."
                    continue
                }
                Configure-Gradle-Memory -Profile "balanced"
                Stop-Gradle-Daemons
                if (Build-APK -BuildType "debug") {
                    Install-APK-On-Device $ApkDebug
                }
            }
            "3" {
                Configure-Gradle-Memory -Profile "aggressive"
                Stop-Gradle-Daemons
                Build-APK -BuildType "release" | Out-Null
                Write-Host ""
                Write-Host "APK: $ApkRelease" -ForegroundColor $Green
                Write-Host "Install manually with: adb install -r $ApkRelease" -ForegroundColor $Yellow
            }
            "4" {
                Stop-Gradle-Daemons
                Clean-Build
                Configure-Gradle-Memory -Profile "balanced"
                Build-APK -BuildType "debug" | Out-Null
            }
            "5" {
                Configure-Gradle-Memory -Profile "conservative"
                Stop-Gradle-Daemons
                Build-APK -BuildType "debug" | Out-Null
            }
            "6" {
                Write-Header "Checking Device Connection"
                $devices = Get-ConnectedDevices
                if ($devices.Count -eq 0) {
                    Write-Host "No devices connected" -ForegroundColor $Yellow
                } else {
                    Write-Host "Connected devices:" -ForegroundColor $Green
                    $devices | ForEach-Object { Write-Host "  • $_" }
                }
            }
            "7" {
                Write-Host ""
                Write-Host "Goodbye!" -ForegroundColor $Green
                exit 0
            }
            default {
                Write-Host "Invalid choice. Try again." -ForegroundColor $Red
            }
        }
        
        Read-Host "`nPress Enter to continue"
    }
}

# Run main
Main
